function changeLanguage(language) {
  const selected = translations[language];

  if (!selected) return;

  const elements = {
    "nav-home": "home",
    "nav-destinations": "destinations",
    "nav-planner": "planner",
    "nav-features": "features",
    "nav-button": "planTrip",
    "hero-eyebrow": "eyebrow",
    "hero-title": "heroTitle",
    "hero-highlight": "heroHighlight",
    "hero-description": "heroDescription",
    "hero-start": "startExploring",
    "hero-discover": "discoverPlaces",
    "stat-countries": "countries",
    "stat-destinations": "destinationsCount",
    "stat-assistant": "assistant",
    "destinations-tag": "explorePlanet",
    "destinations-title": "popularDestinations",
    "destinations-description": "destinationDescription",
    "planner-tag": "smartTravel",
    "planner-title": "journeyTitle",
    "planner-highlight": "journeyHighlight",
    "planner-description": "journeyDescription",
    "planner-destination-label": "destinationQuestion",
    "planner-date-label": "travelDate",
    "planner-travelers-label": "travelers",
    "planner-budget-label": "budget",
    "planner-submit": "createTrip",
    "features-tag": "travelSmarter",
    "features-title": "featureHeading",
    "features-description": "featureDescription",
    "feature-ai-title": "aiAssistant",
    "feature-ai-description": "aiDescription",
    "feature-voice-title": "voiceAssistant",
    "feature-voice-description": "voiceDescription",
    "feature-hotel-title": "hotelDiscovery",
    "feature-hotel-description": "hotelDescription",
    "feature-food-title": "foodFinder",
    "feature-food-description": "foodDescription",
    "feature-budget-title": "budgetPlanner",
    "feature-budget-description": "budgetDescription",
    "feature-local-title": "localExperiences",
    "feature-local-description": "localDescription",
    "footer-description": "footerDescription"
  };

  Object.entries(elements).forEach(([id, key]) => {
    const element = document.getElementById(id);
    if (element && selected[key]) {
      element.textContent = selected[key];
    }
  });

  const destination = document.getElementById("destination");
  if (destination) {
    destination.placeholder = selected.destinationPlaceholder;
  }

  const budget = document.getElementById("budget");
  if (budget) {
    budget.placeholder = selected.budgetPlaceholder;
  }

  document.documentElement.lang = language;
  document.documentElement.dir = language === "ur" ? "rtl" : "ltr";

  try {
    localStorage.setItem("explorex-language", language);
  } catch (error) {
    console.warn("Could not save language preference.");
  }
}

/* INITIALIZE LANGUAGE SELECTOR */

document.addEventListener("DOMContentLoaded", () => {
  const selector = document.getElementById("languageSelect");

  if (!selector) return;

  let savedLanguage = "en";

  try {
    savedLanguage = localStorage.getItem("explorex-language") || "en";
  } catch (error) {
    console.warn("Using default language.");
  }

  selector.value = translations[savedLanguage] ? savedLanguage : "en";
  changeLanguage(selector.value);

  selector.addEventListener("change", () => {
    changeLanguage(selector.value);
  });
});
